import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { BASE, PROFILE_DIR, RUN_DIR } from './common.mjs';
const dir = path.join(RUN_DIR, 'report');
fs.mkdirSync(dir, { recursive: true });
const ctx = await chromium.launchPersistentContext(PROFILE_DIR, { headless: true, viewport: { width: 1400, height: 900 } });
const page = ctx.pages()[0] ?? (await ctx.newPage());
const writes = [];
page.on('request', (r) => { if (r.method() !== 'GET' && r.url().includes('/api/') && !r.url().endsWith('/saved')) writes.push(new URL(r.url()).pathname); });
await page.goto(`${BASE}/report/bank-plan`, { waitUntil: 'networkidle', timeout: 120000 });
const pdfBtn = page.getByRole('button', { name: 'PDFダウンロード' }).first();
await pdfBtn.waitFor({ state: 'visible', timeout: 120000 });
await page.waitForFunction(() => { const b = [...document.querySelectorAll('button')].find((x) => x.innerText.trim() === 'PDFダウンロード'); return b && !b.disabled; }, null, { timeout: 120000 });
const [download] = await Promise.all([page.waitForEvent('download', { timeout: 240000 }), pdfBtn.click({ force: true })]);
const file = path.join(dir, `bank-plan-final-${Date.now()}.pdf`);
await download.saveAs(file);
console.log('PDF', file, fs.statSync(file).size, 'WRITES', JSON.stringify(writes));
await ctx.close();
